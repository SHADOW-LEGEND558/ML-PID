"""Export the frozen final MLP for local browser inference, plus parity fixtures."""
import ast,hashlib,json,sys
from pathlib import Path
import numpy as np
import pandas as pd
import torch

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'src'))
from MLP import MLPModel
from benchmark import FEATURES

def main():
    path=ROOT/'results/dataset_final_10000/standard_mlp.pt'
    bundle=torch.load(path,map_location='cpu',weights_only=True)
    layers=[]
    for name,weight in bundle['state'].items():
        if name.endswith('.weight'):
            layers.append({'weights':weight.tolist(),'bias':bundle['state'][name.replace('.weight','.bias')].tolist()})
    source=(ROOT/'src/benchmark.py').read_text(encoding='utf-8')
    assessor=next(n for n in ast.parse(source).body if isinstance(n,ast.FunctionDef) and n.name=='assess_controller')
    protocol=json.loads((ROOT/'results/dataset_final_10000/evaluation_protocol.json').read_text(encoding='utf-8'))
    frame=pd.read_csv(ROOT/protocol['data_path'])
    training=frame.loc[protocol['train'],FEATURES]
    payload={'name':'Final 10K MLP','features':FEATURES,'layers':layers,'mean':bundle['mean'],
        'std':bundle['std'],'qscale':bundle['qscale'],'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
        'featureRanges':{k:[float(training[k].min()),float(training[k].max())] for k in FEATURES},
        'assessorSource':ast.unparse(assessor),
        'assessorSha256':hashlib.sha256(ast.unparse(assessor).encode()).hexdigest()}
    (ROOT/'docs/model-data.js').write_text('// Frozen final model; generated by scripts/export_browser_model.py.\nwindow.PID_MODEL = '+json.dumps(payload,separators=(',',':'))+';\n',encoding='utf-8')
    # Validation examples check portable inference, not model selection or test rescoring.
    X=frame.loc[protocol['validation'],FEATURES].sample(64,random_state=64)
    model=MLPModel.load(path)
    (ROOT/'results/dataset_final_10000/browser_parity_fixtures.json').write_text(json.dumps({'features':X.values.tolist(),'gains':model.predict(X).tolist()}),encoding='utf-8')
    print('Exported',len(layers),'dense layers;',sum(len(r) for l in layers for r in l['weights']),'weights.')

if __name__=='__main__':main()
