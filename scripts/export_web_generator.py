"""Refresh the browser's Python model snapshot after editing src/data_gen.py.

Run: python scripts/export_web_generator.py
No third-party packages are needed for this export step.
"""
import ast
import hashlib
import json
from pathlib import Path


def export():
    root = Path(__file__).resolve().parents[1]
    source = (root / 'src' / 'data_gen.py').read_text(encoding='utf-8')
    selected = {'Plant', 'PIDGains', 'PlantSimulator', 'FeatureExtractor', 'PIDOptimizer'}
    nodes = [node for node in ast.parse(source).body
             if isinstance(node, ast.ClassDef) and node.name in selected]
    prelude = ('from dataclasses import dataclass\nfrom typing import Optional\n'
               'import numpy as np\nimport scipy.integrate as spi\n'
               'import scipy.optimize as spo\nimport scipy.signal as sps\n')
    browser_source = prelude + '\n\n'.join(ast.unparse(node) for node in nodes)
    payload = {'sha256': hashlib.sha256(source.encode()).hexdigest(),
               'source': browser_source}
    (root / 'docs' / 'generator-source.js').write_text(
        '// Generated by scripts/export_web_generator.py; do not edit by hand.\n'
        'window.PID_GENERATOR = ' + json.dumps(payload) + ';\n', encoding='utf-8')
    print('Exported generator classes to docs/generator-source.js')


if __name__ == '__main__':
    export()
