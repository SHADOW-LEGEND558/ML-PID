import argparse
from pathlib import Path
import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression, Ridge
from sklearn.preprocessing import StandardScaler, PolynomialFeatures
from sklearn.pipeline import make_pipeline
from sklearn.model_selection import train_test_split

# Removed unused EvaluateModel import
from Baselines import Model, Dataset, DataConditioner, BenchmarkRunner


# 1. Feature Scaler implementation of DataConditioner
class StandardDataConditioner(DataConditioner):
    """Standardizes input feature variables (zero mean, unit variance)."""
    
    def __init__(self):
        self.scaler = StandardScaler()

    def fit_transform(self, dataset: Dataset) -> Dataset:
        scaled_features = self.scaler.fit_transform(dataset.features)
        return Dataset(features=scaled_features, targets=dataset.targets.copy())

    def transform(self, dataset: Dataset) -> Dataset:
        scaled_features = self.scaler.transform(dataset.features)
        return Dataset(features=scaled_features, targets=dataset.targets.copy())


# 2. Linear Regression Model Baseline
class LinearRegressionModel(Model):
    def __init__(self):
        self._model = LinearRegression()

    @property
    def name(self) -> str:
        return "Multiple Linear Regression"

    def fit(self, dataset: Dataset) -> None:
        self._model.fit(dataset.features, dataset.targets)

    def predict(self, dataset: Dataset) -> np.ndarray:
        return self._model.predict(dataset.features)


# 3. Ridge Regression Model Baseline
class RidgeRegressionModel(Model):
    def __init__(self, alpha: float = 1.0):
        self.alpha = alpha
        self._model = Ridge(alpha=self.alpha)

    @property
    def name(self) -> str:
        return f"Ridge Regression (alpha={self.alpha})"

    def fit(self, dataset: Dataset) -> None:
        self._model.fit(dataset.features, dataset.targets)

    def predict(self, dataset: Dataset) -> np.ndarray:
        return self._model.predict(dataset.features)


# 4. Polynomial Ridge Regression Model Baseline
class PolynomialRegressionModel(Model):
    def __init__(self, degree: int = 2, alpha: float = 1.0):
        self.degree = degree
        self.alpha = alpha
        self._model = make_pipeline(
            PolynomialFeatures(degree=self.degree, include_bias=False),
            Ridge(alpha=self.alpha)
        )

    @property
    def name(self) -> str:
        return f"Polynomial Ridge Regression (degree={self.degree})"

    def fit(self, dataset: Dataset) -> None:
        self._model.fit(dataset.features, dataset.targets)

    def predict(self, dataset: Dataset) -> np.ndarray:
        return self._model.predict(dataset.features)


def load_dataset(csv_path: str | Path) -> tuple[Dataset, list[str], list[str]]:
    """Loads CSV dataset generated by data_gen.py into Dataset object."""
    df = pd.read_csv(csv_path)
    
    feature_cols = ["t_rise", "t_settling", "y_peak", "y_ss", "AUC", "tau_est"]
    target_cols = ["Kp", "Ki", "Kd"]
    
    for col in feature_cols + target_cols:
        if col not in df.columns:
            raise KeyError(f"Required column '{col}' missing in dataset {csv_path}")

    features = df[feature_cols].values
    targets = df[target_cols].values
    return Dataset(features=features, targets=targets), feature_cols, target_cols


def print_detailed_metrics(model: Model, test_dataset: Dataset, target_names: list[str]) -> None:
    """Prints target-wise breakdown of MSE, MAE, and R2 score for Kp, Ki, Kd."""
    preds = model.predict(test_dataset)
    targets = test_dataset.targets
    print(f"--- Detailed Target Breakdown for {model.name} ---")
    for i, name in enumerate(target_names):
        y_true = targets[:, i]
        y_pred = preds[:, i]
        mse = np.mean((y_pred - y_true) ** 2)
        mae = np.mean(np.abs(y_pred - y_true))
        ss_res = np.sum((y_true - y_pred) ** 2)
        ss_tot = np.sum((y_true - np.mean(y_true)) ** 2)
        r2 = 1.0 - (ss_res / (ss_tot + 1e-8))
        print(f"  {name:4s} -> MSE: {mse:10.4f} | MAE: {mae:8.4f} | R2: {r2:7.4f}")
    print()


def main():
    parser = argparse.ArgumentParser(description="Train and evaluate Linear Regression baselines on PID dataset.")
    parser.add_argument("--data", type=Path, default=Path("data/pid_dataset.csv"), help="Path to PID dataset CSV file")
    parser.add_argument("--test-size", type=float, default=0.2, help="Fraction of test dataset split")
    parser.add_argument("--seed", type=int, default=42, help="Random seed for train/test split")
    args = parser.parse_args()

    data_path: Path = args.data
    if not data_path.exists():
        print(f"Dataset path '{data_path}' does not exist.")
        print("Please run data_gen.py first to generate the dataset!")
        return

    full_dataset, feature_names, target_names = load_dataset(data_path)
    
    # Train / Test split
    X_train, X_test, y_train, y_test = train_test_split(
        full_dataset.features, full_dataset.targets, test_size=args.test_size, random_state=args.seed
    )
    
    raw_train = Dataset(features=X_train, targets=y_train)
    raw_test = Dataset(features=X_test, targets=y_test)

    # Initialize conditioner & benchmark runner
    conditioner = StandardDataConditioner()
    runner = BenchmarkRunner(conditioner=conditioner)

    # Register models
    runner.add_model(LinearRegressionModel())
    runner.add_model(RidgeRegressionModel(alpha=10.0))
    runner.add_model(PolynomialRegressionModel(degree=2, alpha=10.0))

    # Run benchmark pipeline
    results = runner.run_benchmark(raw_train, raw_test)

    # Overall Summary Report
    print("\n=======================================================")
    print("           BENCHMARK RESULTS (Linear Baselines)        ")
    print("=======================================================")
    for res in results:
        print(f"Model: {res.model_name}")
        print(f"  Overall MSE : {res.mse:.4f}")
        print(f"  Overall MAE : {res.mae:.4f}")
        print(f"  Overall R2  : {res.r2_score:.4f}")
        print("-------------------------------------------------------")

    # Target-wise per gain evaluation
    clean_test = conditioner.transform(raw_test)
    print()
    for model in runner.models:
        print_detailed_metrics(model, clean_test, target_names)


if __name__ == "__main__":
    main()